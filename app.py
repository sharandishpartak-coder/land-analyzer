# -*- coding: utf-8 -*-
"""
تحلیل تعاملی دو سناریوی توافق زمین:
  ۱) ۶۰٪ + ۱/۲۰ متر
  ۲) ۷۰٪
نویسنده: توسعه‌دهنده ارشد Python – سیستم‌های تصمیم‌یار املاک
"""

import streamlit as st
import pandas as pd
import matplotlib.pyplot as plt

# ---------------------------------------------------------
# تنظیمات صفحه + استایل راست‌چین (RTL)
# ---------------------------------------------------------
st.set_page_config(
    page_title="تحلیل توافق زمین",
    page_icon="🏗️",
    layout="wide",
)

st.markdown(
    """
    <style>
        html, body, [class*="css"], .stApp {
            direction: rtl;
            text-align: right;
            font-family: 'Vazirmatn', 'Tahoma', sans-serif;
        }
        table, .stDataFrame { direction: rtl; text-align: right; }
        h1, h2, h3, h4, h5, h6, p, label { text-align: right; }
        .stNumberInput input { text-align: right; }
    </style>
    """,
    unsafe_allow_html=True,
)

st.title("🏗️ تحلیل و مقایسه دو سناریوی توافق زمین")
st.caption("سناریو ۱: ۶۰٪ + ۱/۲۰ متر | سناریو ۲: ۷۰٪")

# ---------------------------------------------------------
# ورودی‌های کاربر
# ---------------------------------------------------------
st.subheader("📥 ورودی‌ها")
col1, col2, col3 = st.columns(3)

with col1:
    W = st.number_input("عرض زمین (متر)", min_value=1.0, value=12.0, step=0.5)
with col2:
    L = st.number_input("طول زمین (متر)", min_value=1.0, value=30.0, step=0.5)
with col3:
    P = st.number_input("قیمت هر مترمربع (میلیون تومان)", min_value=1.0, value=50.0, step=1.0)

# ---------------------------------------------------------
# محاسبات
# ---------------------------------------------------------
# سناریو ۶۰٪ + ۱/۲۰ متر
L60 = 0.60 * L + 1.20
A60 = L60 * W
V60 = A60 * P
R60 = L60 / W

# سناریو ۷۰٪
L70 = 0.70 * L
A70 = L70 * W
V70 = A70 * P
R70 = L70 / W

# اختلاف‌ها
dL = L70 - L60
dA = A70 - A60
dV = V70 - V60

# ---------------------------------------------------------
# تابع هشدار تناسبات
# ---------------------------------------------------------
def tartib_warning(R: float) -> str:
    if R < 1.30:
        return "🟢 عالی / فشرده"
    elif R <= 1.60:
        return "🟡 مناسب"
    else:
        return "🟠 کشیده — با توجه به دوبر کوچه شمالی-جنوبی قابل مدیریت است"

# ---------------------------------------------------------
# جدول مقایسه
# ---------------------------------------------------------
st.subheader("📊 جدول مقایسه دو سناریو")

df_compare = pd.DataFrame(
    {
        "سناریو": ["۶۰٪ + ۱/۲۰ متر", "۷۰٪"],
        "طول نهایی (m)": [round(L60, 2), round(L70, 2)],
        "مساحت (m²)": [round(A60, 2), round(A70, 2)],
        "نسبت L/W": [round(R60, 2), round(R70, 2)],
        "ارزش زمین (میلیون تومان)": [round(V60, 2), round(V70, 2)],
        "هشدار تناسبات": [tartib_warning(R60), tartib_warning(R70)],
    }
)
st.dataframe(df_compare, use_container_width=True, hide_index=True)

# ---------------------------------------------------------
# جدول اختلاف‌ها
# ---------------------------------------------------------
st.subheader("🔻 جدول اختلاف (سناریو ۷۰٪ منهای ۶۰٪)")

df_diff = pd.DataFrame(
    {
        "شاخص": ["اختلاف طول (m)", "اختلاف مساحت (m²)", "اختلاف ارزش (میلیون تومان)"],
        "مقدار": [round(dL, 2), round(dA, 2), round(dV, 2)],
    }
)
st.dataframe(df_diff, use_container_width=True, hide_index=True)

# ---------------------------------------------------------
# نمودار میله‌ای ساده
# ---------------------------------------------------------
st.subheader("📈 نمودار مقایسه ارزش زمین")
chart_df = pd.DataFrame(
    {"ارزش (میلیون تومان)": [V60, V70]},
    index=["۶۰٪ + ۱/۲۰", "۷۰٪"],
)

fig, ax = plt.subplots(figsize=(6, 3.5))
bars = ax.bar(chart_df.index, chart_df["ارزش (میلیون تومان)"], color=["#4C9F70", "#1F6FEB"])
ax.set_ylabel("ارزش (میلیون تومان)")
ax.set_title("مقایسه ارزش زمین در دو سناریو")
for b in bars:
    ax.text(
        b.get_x() + b.get_width() / 2,
        b.get_height(),
        f"{b.get_height():,.0f}",
        ha="center",
        va="bottom",
        fontsize=10,
    )
plt.xticks(rotation=0)
st.pyplot(fig)

# ---------------------------------------------------------
# هشدار تناسبات به‌صورت جداگانه
# ---------------------------------------------------------
st.subheader("⚠️ هشدار تناسبات")
col_a, col_b = st.columns(2)
with col_a:
    st.info(f"**سناریو ۶۰٪:** R = {R60:.2f} → {tartib_warning(R60)}")
with col_b:
    st.info(f"**سناریو ۷۰٪:** R = {R70:.2f} → {tartib_warning(R70)}")

# ---------------------------------------------------------
# تحلیل طراحی دوبر کوچه
# ---------------------------------------------------------
st.subheader("🏘️ تحلیل طراحی (دوبر کوچه شمالی–جنوبی)")
st.markdown(
    """
    - **نور شمالی:** نور یکنواخت و بدون تابش مستقیم — مناسب اتاق خواب، آشپزخانه، فضای کار.  
    - **نور جنوبی:** تابش مستقیم زمستانی — مناسب نشیمن، پذیرایی، تراس.  
    - **حیاط میانی پیشنهادی:** در سناریو ۷۰٪ به دلیل طول ۲۱ متری، حتماً یک **حیاط یا نورگیر میانی ۳–۴ متری** قرار دهید تا عمق پلان از هر دو جبهه تغذیه شود.  
    - **پارکینگ:** با ورودی از کوچه شمالی و واحدها با ورودی از کوچه جنوبی — جداسازی عملکردی مطلوب.  
    - **محدودیت کشیدگی:** چون هر دو جبهه باز است، کشیدگی R>1.60 محدودیت جدی ایجاد نمی‌کند؛ فقط هزینه نما و تأسیسات افزایش می‌یابد.
    """
)

# ---------------------------------------------------------
# پیشنهاد نهایی
# ---------------------------------------------------------
st.subheader("✅ پیشنهاد نهایی")
if dV > 0 and R70 <= 1.75:
    st.success(
        f"**سناریو ۷۰٪ پیشنهاد می‌شود.** ارزش زمین {dV:,.0f} میلیون تومان بیشتر است "
        f"و با توجه به دوبر کوچه بودن زمین، کشیدگی R={R70:.2f} قابل مدیریت است."
    )
elif dV > 0:
    st.warning(
        f"سناریو ۷۰٪ ارزش بیشتری ({dV:,.0f} میلیون) دارد، اما نسبت L/W = {R70:.2f} "
        f"کشیدگی قابل‌توجهی ایجاد می‌کند. طراحی با حیاط میانی الزامی است."
    )
else:
    st.info("سناریو ۶۰٪ + ۱/۲۰ از نظر تناسبات و هزینه ساخت مناسب‌تر است.")

st.caption(
    "این تحلیل یک ابزار کمک‌تصمیم است؛ برای توافق نهایی، بررسی حقوقی سند، "
    "ضوابط شهرداری و طرح تفصیلی الزامی است."
)